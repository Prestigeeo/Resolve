from typing import List
from ..schemas.case import IncidentCategory, ExtractedCaseFacts, PaymentMethod
from ..schemas.guidance import EvidenceItem

class EvidenceChecklistBuilder:
    """
    Builds category-specific, actionable evidence checklists for Nigerian consumers.
    """

    @classmethod
    def build_checklist(cls, facts: ExtractedCaseFacts) -> List[EvidenceItem]:
        items: List[EvidenceItem] = []
        category = facts.category

        # ---------------------------------------------------------------------
        # Category 1: Failed Bank Transfer
        # ---------------------------------------------------------------------
        if category == IncidentCategory.FAILED_TRANSFER:
            items.append(
                EvidenceItem(
                    id="ev_debit_alert_or_statement",
                    title="Debit Alert / Account Statement",
                    description="Screenshot or PDF showing date, time, and exact amount debited from your account.",
                    is_mandatory=True,
                    is_collected=False
                )
            )
            items.append(
                EvidenceItem(
                    id="ev_session_id_receipt",
                    title="Transaction Receipt Showing 30-Digit NIBSS Session ID",
                    description="The receipt generated by your bank app showing the 30-digit NIBSS Session ID.",
                    is_mandatory=True,
                    is_collected=bool(facts.session_id_or_ref)
                )
            )
            items.append(
                EvidenceItem(
                    id="ev_recipient_statement",
                    title="Recipient Confirmation / Statement of Non-Receipt",
                    description="Screenshot of message or statement from recipient proving funds did not enter their account.",
                    is_mandatory=False,
                    is_collected=False
                )
            )
            if facts.provider_contacted:
                items.append(
                    EvidenceItem(
                        id="ev_bank_ticket_proof",
                        title="Initial Bank Complaint Ticket Reference",
                        description="SMS or email from your bank showing the complaint ticket reference number.",
                        is_mandatory=True,
                        is_collected=bool(facts.existing_ticket_ref)
                    )
                )

        # ---------------------------------------------------------------------
        # Category 2: Undelivered Airtime / Data
        # ---------------------------------------------------------------------
        elif category == IncidentCategory.UNDELIVERED_AIRTIME_DATA:
            items.append(
                EvidenceItem(
                    id="ev_airtime_payment_receipt",
                    title="Bank or Payment Channel Debit Confirmation",
                    description="Proof of debit for the airtime/data purchase showing timestamp and amount.",
                    is_mandatory=True,
                    is_collected=False
                )
            )
            items.append(
                EvidenceItem(
                    id="ev_telco_balance_screenshot",
                    title="Current Airtime / Data Balance Screenshot",
                    description="Dial *310# (or network USSD) and take a screenshot showing that the value was not added.",
                    is_mandatory=True,
                    is_collected=False
                )
            )
            if facts.provider_contacted:
                items.append(
                    EvidenceItem(
                        id="ev_telco_ticket_id",
                        title="Telco Customer Care Complaint Ticket ID",
                        description="SMS from telco (e.g. MTN, Airtel) confirming your complaint reference.",
                        is_mandatory=True,
                        is_collected=bool(facts.existing_ticket_ref)
                    )
                )

        # ---------------------------------------------------------------------
        # Category 3: Stolen Funds / Fraud
        # ---------------------------------------------------------------------
        elif category == IncidentCategory.STOLEN_FUNDS_FRAUD:
            items.append(
                EvidenceItem(
                    id="ev_unauthorized_debit_alerts",
                    title="All Unauthorized Debit Alerts & Receipts",
                    description="Screenshots of all debit SMS/emails with timestamps and recipient account details.",
                    is_mandatory=True,
                    is_collected=False
                )
            )
            items.append(
                EvidenceItem(
                    id="ev_beneficiary_account_details",
                    title="Beneficiary Account Number & Bank Name",
                    description="The receiving account number, bank/fintech name (e.g., OPay, Moniepoint, PalmPay), and account name.",
                    is_mandatory=True,
                    is_collected=bool(facts.recipient_institution)
                )
            )
            items.append(
                EvidenceItem(
                    id="ev_police_extract_or_npf_receipt",
                    title="Police Extract / NPF-NCCC Cybercrime e-Report Acknowledgment",
                    description="Mandatory for banks to permanently reverse funds from a 3rd party account under Nigerian law.",
                    is_mandatory=True,
                    is_collected=False
                )
            )

        # ---------------------------------------------------------------------
        # Category 4: Merchant Non-Delivery
        # ---------------------------------------------------------------------
        elif category == IncidentCategory.MERCHANT_NON_DELIVERY:
            items.append(
                EvidenceItem(
                    id="ev_proof_of_payment",
                    title="Proof of Payment (Transfer Receipt or Gateway Checkout)",
                    description="Receipt showing successful transfer to merchant account or gateway reference ID.",
                    is_mandatory=True,
                    is_collected=bool(facts.amount_ngn)
                )
            )
            items.append(
                EvidenceItem(
                    id="ev_order_agreement_screenshots",
                    title="Order Confirmation & Promised Delivery Date",
                    description="Screenshots of chat (WhatsApp, Instagram DM, email) showing item description and promised delivery date.",
                    is_mandatory=True,
                    is_collected=False
                )
            )
            items.append(
                EvidenceItem(
                    id="ev_chat_refusal_or_blocking_proof",
                    title="Proof of Non-Delivery / Merchant Excuses / Blocking",
                    description="Screenshots showing unanswered follow-ups, refusal to refund, or that the merchant blocked you.",
                    is_mandatory=True,
                    is_collected=False
                )
            )
            items.append(
                EvidenceItem(
                    id="ev_merchant_identifier_profile",
                    title="Merchant Handle, Phone Number, and Bank Account",
                    description="Screenshot of merchant's profile page, contact numbers, and bank account details used.",
                    is_mandatory=False,
                    is_collected=bool(facts.merchant_name_or_handle)
                )
            )

        return items
